def backup_existing_file(path: Path) -> Optional[Path]:
    """If *path* exists, rename it to the next numbered backup before it is overwritten.

    name.sh -> name.1.sh, name.2.sh, ... (highest number = most recent), so the commands
    of earlier runs are kept. Files not ending in .sh become name.1, name.2, ...
    Returns the backup path, or None if *path* did not exist.
    """
    path = Path(path)
    if not path.exists():
        return None
    stem, suffix = (path.stem, path.suffix) if path.suffix == ".sh" else (path.name, "")
    prefix = stem + "."
    max_n = 0
    for p in path.parent.iterdir():
        name = p.name
        if name.startswith(prefix) and name.endswith(suffix):
            n = name[len(prefix):len(name) - len(suffix)]
            if n.isdigit():
                max_n = max(max_n, int(n))
    backup = path.with_name(f"{stem}.{max_n + 1}{suffix}")
    path.rename(backup)
    return backup


def set_command_script_path(path: Path) -> None:
    """Set the global path for logging commands."""
    global _command_script_path
    _command_script_path = path
    backup = backup_existing_file(path)
    if backup:
        print(f"Previous commands file kept as: {backup}")
    # Initialize the script with a header
    with path.open("w", encoding="utf-8") as f:
        f.write("#!/bin/bash\n")
        f.write("# GROMACS PCA analysis commands\n")
        f.write("# Generated by gmx_pca.py\n")
        f.write(f"# Invocation: {' '.join(sys.argv)}\n")
        f.write(f"# Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
        f.write("#\n")
        f.write("# This script reproduces all GROMACS commands executed by the Python script.\n")
        f.write("# You can run this independently to get the same results (the index of the\n")
        f.write("# reduced structure, pca_groups.ndx, is written by gmx_pca.py itself).\n")
        f.write("#\n\n")
        f.write("set -e  # Exit on error\n\n")
        # the GROMACS commands run in the output folder (their own logs and backups go there)
        f.write(f"cd '{path.parent}'\n")
        f.write("export GMX_MAXBACKUP=-1  # no #file.N# backups: the folder belongs to this analysis\n\n")


def shell_quote(arg: str) -> str:
    """An argument as the shell needs it (quoted if it contains anything special)."""
    return arg if re.fullmatch(r"[\w@%+=:,./-]+", arg) else "'" + arg.replace("'", "'\\''") + "'"


def log_command_to_script(script_path: Path, cmd: List[str], stdin: Optional[str] = None, comment: Optional[str] = None) -> None:
    """Append a command to the reproducibility script."""
    with script_path.open("a", encoding="utf-8") as f:
        if comment:
            f.write(f"\n# {comment}\n")
        cmd_str = " ".join(shell_quote(arg) for arg in cmd)
        if stdin:
            stdin_clean = stdin.rstrip()
            if "\n" in stdin_clean:
                f.write(f"{cmd_str} <<'EOF'\n{stdin_clean}\nEOF\n")
            else:
                f.write(f"echo {shell_quote(stdin_clean)} | {cmd_str}\n")
        else:
            f.write(f"{cmd_str}\n")


def run_cmd(cmd: List[str], stdin: Optional[str] = None, cwd: Optional[Path] = None, comment: Optional[str] = None) -> subprocess.CompletedProcess:
    """Run a command (logged to the command script) and raise CommandError on a non-zero
    return code. stdout and stderr are captured together."""
    if _command_script_path:
        log_command_to_script(_command_script_path, cmd, stdin, comment)
    proc = subprocess.run(
        cmd,
        input=stdin.encode() if stdin is not None else None,
        cwd=str(cwd) if cwd else (str(_command_script_path.parent) if _command_script_path else None),
        # no #file.N# backups when an analysis is re-run: the output folder belongs to it
        env=dict(os.environ, GMX_MAXBACKUP="-1"),
        check=False,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
    )
    if proc.returncode != 0:
        output = proc.stdout.decode(errors="replace")
        where = ""
        if _command_script_path:
            log = _command_script_path.parent / "logs" / f"failed_{Path(cmd[0]).name}_{cmd[1]}.log"
            try:
                log.parent.mkdir(parents=True, exist_ok=True)
                log.write_text(f"$ {' '.join(cmd)}\n\n{output}")
                where = f" (full output: {log})"
            except OSError:
                pass
        raise CommandError(f"gmx {cmd[1]} failed: {gromacs_error(output)}{where}")
    return proc


def gromacs_error(output: str) -> str:
    """The message of a GROMACS error: the lines after its "Fatal error:" / "Error in user input:"
    heading, up to the dashed line (else the last lines of the output)."""
    lines = output.splitlines()
    for i, line in enumerate(lines):
        if line.startswith(("Fatal error", "Error in user input", "Inconsistency in user input")):
            message = []
            for follow in lines[i + 1:]:
                if follow.startswith("-----") or follow.startswith("For more information"):
                    break
                if follow.strip():
                    message.append(follow.strip())
            return " ".join(message) or line.strip()
    rest = [l.strip() for l in lines if l.strip()]
    return " | ".join(rest[-3:]) if rest else "no output"


def which_gmx(user_bin: Optional[str]) -> str:
    """Find the GROMACS binary to use: --gmx-bin, $GMX_BIN, gmx or gmx_mpi on PATH."""
    candidates: List[Optional[str]] = [
        user_bin,
        os.environ.get("GMX_BIN"),
        shutil.which("gmx"),
        shutil.which("gmx_mpi"),
    ]
    for c in candidates:
        if c and (shutil.which(c) or (Path(c).exists() and os.access(c, os.X_OK))):
            return c
    raise FileNotFoundError(
        "No GROMACS binary found. Install GROMACS or provide --gmx-bin or set $GMX_BIN."
    )


def file_signature(path: Path) -> dict:
    """What identifies an input file's contents cheaply: path, size, modification time."""
    st = path.stat()
    return {"path": str(path), "size": st.st_size, "mtime": round(st.st_mtime, 3)}


def preprocessing_params(s: Path, f: Path, selection: str, fit_selection: str, pbc: str,
                         center: bool, fit: Optional[str], frames: dict) -> dict:
    """Everything the index, fitted trajectory and reference structure depend on."""
    return {"structure": file_signature(s), "trajectory": file_signature(f), "selection": selection,
            "fit_selection": fit_selection, "pbc": pbc, "center": center, "fit": fit or "none",
            "frames": frames}


