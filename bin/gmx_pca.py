def main_multi(args: argparse.Namespace, outdir: Path, fit_selection: str, frames: dict) -> int:
    """gmx_pca.py with several trajectories (-f t1 t2 ... or --trajectories)."""
    try:
        if args.trajectories is not None:
            default_s = Path(args.structure[0]).expanduser().resolve() if args.structure else None
            table = Path(args.trajectories).expanduser().resolve()
            if not table.exists():
                raise AnalysisError(f"--trajectories file not found: {table}")
            trajs = read_trajectory_table(table, default_s)
        else:
            trajs = trajectories_from_args(args.trajectory, args.structure, args.labels, args.groups)
        if len(trajs) < 2:
            raise AnalysisError("--trajectories lists one trajectory: give it with -f and -s instead")
        check_trajectories(trajs, args.pbc)
        by_group = args.color_by == "group"
        if by_group and any(t.group is None for t in trajs):
            raise AnalysisError("--color-by group: give every trajectory a group "
                                f"(none for {', '.join(t.label for t in trajs if t.group is None)})")
        basis, basis_desc = select_basis(trajs, args.pca_from or "all")
        gmx = which_gmx(args.gmx_bin)
    except (AnalysisError, FileNotFoundError) as e:
        print(f"Error: {e}", file=sys.stderr)
        return 2

    width = max(len(t.label) for t in trajs)
    print(f"{len(trajs)} trajectories; PCA of {basis_desc}:")
    for t in trajs:
        print(f"  {t.label:<{width}}  {t.group or '-':<8}  {t.trajectory}  ({t.structure.name})"
              + ("  *" if t in basis and len(basis) < len(trajs) else ""))
    ensure_outdir(outdir)
    log_dir = outdir / "logs"
    ensure_outdir(log_dir)
    command_script = outdir / args.commands_file
    set_command_script_path(command_script)
    fit_mode = None if args.fit in ("", "none") else args.fit
    try:
        eigenvalues, percent, cumulative, projections, fitted = run_multi(
            gmx, trajs, basis, basis_desc, outdir, log_dir, args.selection, fit_selection, args.pbc,
            not args.no_center, fit_mode, frames, args.first, args.last, args.overwrite)
        print("  Mean and standard deviation of the projections (nm; also in projection_stats.txt):")
        projection_stats(trajs, projections, basis_desc, outdir / "projection_stats.txt")
        group_files = write_group_projections(trajs, projections, outdir)
        if args.rmsip:
            print("[4b] RMSIP: how similar the motions of the trajectories and groups are...")
            first_pc = sorted(projections[trajs[0].label])[0]
            times = {t.label: np.loadtxt(projections[t.label][first_pc], comments=("#", "@"), ndmin=2)[:, 0]
                     for t in trajs}
            run_rmsip_multi(gmx, trajs, fitted, times, outdir / "fit.gro", outdir / "pca_groups.ndx", outdir,
                            log_dir, args.rmsip_pcs, plots=not args.no_plots and plt is not None)
    except (CommandError, AnalysisError) as e:
        print(f"Error: {e}", file=sys.stderr)
        return 1

    if args.no_plots:
        print("[5/5] Skipping plotting as requested (--no-plots)")
    elif plt is None:
        print("Matplotlib not available; cannot create plots. Install matplotlib or use --no-plots.", file=sys.stderr)
        return 3
    else:
        print("[5/5] Plots...")
        plot_variance(percent, cumulative, outdir)
        plot_multi_projections(trajs, projections, by_group, basis_desc, outdir)
    plot_script = write_multi_plot_script(outdir, trajs, projections, group_files, by_group, basis_desc,
                                          len(eigenvalues))
    print("Done. Outputs in:", outdir)
    print(f"All GROMACS commands have been logged to: {command_script}")
    print(f"plot_xvg.py commands for the plots, to edit and re-run: {plot_script}")
    return 0


def main(argv: Optional[List[str]] = None) -> int:
    p = argparse.ArgumentParser(description="Automate GROMACS PCA and produce plots.")
    p.add_argument("-s", "--structure", nargs="+", default=None,
                   help="The run input file (.tpr), needed to make molecules whole; a GRO/PDB only with --pbc no. "
                        "Several trajectories: one for all, or one per trajectory")
    p.add_argument("-f", "--trajectory", nargs="+", default=None,
                   help="Trajectory file (XTC/TRR); several for a PCA of several trajectories")
    p.add_argument("--trajectories", default=None, metavar="FILE",
                   help="Several trajectories from a file, one per line: 'label group trajectory [structure]' "
                        "(group '-' for none; without structure, the one given with -s)")
    p.add_argument("--labels", nargs="+", default=None,
                   help="With several -f: a label for each trajectory (default: from the file names)")
    p.add_argument("--groups", nargs="+", default=None,
                   help="With several -f: a group for each trajectory, e.g. apo apo holo holo ('-' for none)")
    p.add_argument("--pca-from", default=None, metavar="all|GROUP|LABEL",
                   help="Several trajectories: the PCA of all of them together (default: all), of one group, "
                        "or of one trajectory; every trajectory is projected on its PCs")
    p.add_argument("--color-by", default=None, choices=["trajectory", "group"],
                   help="Several trajectories: one colour per trajectory (default) or per group in the plots")
    p.add_argument("-o", "--outdir", default="pca_out", help="Output directory (default: pca_out)")
    p.add_argument("--selection", default="Backbone",
                   help="GROMACS selection of the atoms analysed: the PCA is of their coordinates (default: Backbone)")
    p.add_argument("--fit-selection", default=None,
                   help="GROMACS selection of the atoms used for fitting and centring (default: --selection), "
                        "e.g. fit on the protein's backbone and analyse a ligand, a loop or the N-terminus")
    p.add_argument("-b", "--begin", type=float, default=None,
                   help="First frame to use, in the unit of --tu (default: the first frame)")
    p.add_argument("-e", "--end", type=float, default=None,
                   help="Last frame to use, in the unit of --tu (default: the last frame)")
    p.add_argument("--dt", type=float, default=None,
                   help="Only use frames spaced by this interval, always in ps (default: every frame)")
    p.add_argument("--tu", default="ps", choices=list(TIME_UNITS_PS),
                   help="Unit of --begin/--end (default: ps); --dt is always in ps")
    p.add_argument("--first", type=int, default=1, help="First PC projected and plotted (default: 1)")
    p.add_argument("--last", type=int, default=2, help="Last PC projected and plotted (default: 2)")
    p.add_argument("--pbc", default="mol", choices=["no", "mol", "res", "atom", "nojump"],
                   help="PBC treatment (default: mol). nojump: molecules made whole, then no jumps across "
                        "the box edge between frames (for long runs)")
    p.add_argument("--no-center", action="store_true", help="Do not center trajectory")
    p.add_argument("--fit", default="rot+trans", choices=["", "none", "rot+trans", "progressive"], help="Fitting mode for trjconv (default: rot+trans). Use 'none' or '' to disable.")
    p.add_argument("--rmsip", action="store_true",
                   help="Also compare the motions with separate PCAs: the RMSIP of their first PCs, first vs second "
                        "half of each trajectory (convergence) and, with several trajectories, trajectory vs "
                        "trajectory and group vs group")
    p.add_argument("--rmsip-pcs", type=int, default=10, help="PCs compared with --rmsip (default: 10)")
    p.add_argument("--gmx-bin", default=None, help="GROMACS binary to use (e.g., gmx or full path)")
    p.add_argument("--no-plots", action="store_true", help="Skip plotting (still runs GROMACS steps)")
    p.add_argument("--overwrite", action="store_true",
                   help="Make the index, fitted trajectory and reference again, even when the ones in --outdir could be reused")
    p.add_argument("--commands-file", default="gmx_pca_commands.sh", help="Output file for command logging, relative to --outdir (default: gmx_pca_commands.sh)")

    args = p.parse_args(argv)
    fit_selection = args.fit_selection or args.selection
    multi = args.trajectories is not None or (args.trajectory is not None and len(args.trajectory) > 1)
    if args.trajectories is not None and args.trajectory is not None:
        p.error("give the trajectories either with -f or with --trajectories, not both")
    if args.trajectory is None and args.trajectories is None:
        p.error("give a trajectory with -f (or several with -f or --trajectories)")
    if not multi:
        for name, value in (("--labels", args.labels), ("--groups", args.groups),
                            ("--pca-from", args.pca_from), ("--color-by", args.color_by)):
            if value is not None:
                p.error(f"{name} is for several trajectories (-f t1.xtc t2.xtc ... or --trajectories)")
        if args.structure is None or len(args.structure) != 1:
            p.error("give one structure (.tpr) with -s")
    elif args.trajectories is not None:
        if args.labels is not None or args.groups is not None:
            p.error("--labels and --groups are for -f; with --trajectories the labels and groups are in the file")
        if args.structure is not None and len(args.structure) != 1:
            p.error("with --trajectories, -s gives one structure, for the trajectories without one in the file")
    elif args.structure is None:
        p.error("give the structure (.tpr) with -s: one for all trajectories or one per trajectory")
    if multi and args.fit == "progressive":
        p.error("--fit progressive fits each frame to the one before, so the trajectories would not share "
                "a reference: use rot+trans with several trajectories")
    if args.first < 1 or args.last < args.first:
        p.error(f"--first and --last must satisfy 1 <= first <= last (got {args.first}, {args.last})")
    scale = TIME_UNITS_PS[args.tu]
    begin_ps = args.begin * scale if args.begin is not None else None
    end_ps = args.end * scale if args.end is not None else None
    if begin_ps is not None and end_ps is not None and end_ps <= begin_ps:
        p.error(f"--end must be after --begin (got {args.begin} and {args.end} {args.tu})")
    if args.dt is not None and args.dt <= 0:
        p.error("--dt must be positive")
    if args.rmsip_pcs < 1:
        p.error("--rmsip-pcs must be at least 1")
    frames = {"begin_ps": begin_ps, "end_ps": end_ps, "dt_ps": args.dt}

    outdir = Path(args.outdir).expanduser().resolve()
    if multi:
        return main_multi(args, outdir, fit_selection, frames)

    # Resolve paths
    s = Path(args.structure[0]).expanduser().resolve()
    f = Path(args.trajectory[0]).expanduser().resolve()

    # Basic checks (before anything is written)
    if not s.exists():
        print(f"Error: structure file not found: {s}", file=sys.stderr)
        return 2
    if not f.exists():
        print(f"Error: trajectory file not found: {f}", file=sys.stderr)
        return 2
    if args.pbc != "no" and s.suffix.lower() != ".tpr":
        # trjconv -pbc mol/res/whole needs the topology to make molecules whole; with a GRO/PDB
        # it only warns and the molecules stay broken, which silently corrupts the PCA
        print(f"Error: --pbc {args.pbc} needs a .tpr as structure (-s), to make molecules whole;"
              f" {s.name} has no topology. Give the run's .tpr, or use --pbc no if the trajectory"
              f" is already whole and centred.", file=sys.stderr)
        return 2
    try:
        gmx = which_gmx(args.gmx_bin)
    except FileNotFoundError as e:
        print(str(e), file=sys.stderr)
        return 2

    ensure_outdir(outdir)
    log_dir = outdir / "logs"
    ensure_outdir(log_dir)
    command_script = outdir / args.commands_file
    set_command_script_path(command_script)

    full_ndx = outdir / "selection.ndx"
    pca_ndx = outdir / "pca_groups.ndx"
    fit_xtc = outdir / "fit.xtc"
    fit_gro = outdir / "fit.gro"
    do_center = not args.no_center
    fit_mode = None if args.fit in ("", "none") else args.fit

    try:
        # The index, fitted trajectory and reference structure of an earlier run in this folder
        # are reused only if they were made from the same files with the same options (recorded
        # in preprocessing.json); otherwise, or with --overwrite, they are made again
        params_file = outdir / "preprocessing.json"
        params = preprocessing_params(s, f, args.selection, fit_selection, args.pbc, do_center, fit_mode, frames)
        reason = None if args.overwrite else reuse_reason(params_file, params, [full_ndx, pca_ndx, fit_xtc, fit_gro])
        if reason == "":
            print(f"[skip] Reusing the index, fitted trajectory and reference structure in {outdir}"
                  f" (same input files and options; --overwrite to make them again)")
            groups = read_ndx(pca_ndx)
            n_analysis, n_fit = len(groups[GROUP_ANALYSIS][1]), len(groups[GROUP_FIT][1])
        else:
            if reason:
                print(f"Note: not reusing the earlier preprocessing in {outdir}: {reason}")
            if params_file.exists():
                params_file.unlink()
            print(f"[1/5] Index groups: analysed '{args.selection}', fitted '{fit_selection}'")
            n_all, n_analysis, n_fit = build_index(gmx, s, args.selection, fit_selection, full_ndx, pca_ndx, log_dir)
            print(f"      {n_analysis} atoms analysed, {n_fit} fitted, {n_all} kept")
            chosen = describe_frames(begin_ps, end_ps, args.dt)
            print(f"[2/5] PBC treatment ({args.pbc}), centring and fitting (trjconv), {chosen}...")
            fit_gro = trj_fit_center(gmx, s, f, full_ndx, pca_ndx, fit_xtc, args.pbc, do_center, fit_mode,
                                     log_dir, frame_options(begin_ps, end_ps, args.dt))
            params_file.write_text(json.dumps(params, indent=2) + "\n")

        print("[3/5] Covariance analysis (covar)...")
        ev_xvg, ev_trr, avg_pdb, trace = run_covar(gmx, fit_gro, fit_xtc, pca_ndx, outdir, log_dir)
        eigenvalues = read_eigenvalues(ev_xvg)
        if args.last > len(eigenvalues):
            raise AnalysisError(f"--last {args.last}, but there are only {len(eigenvalues)} PCs "
                                f"(at most 3 x {n_analysis} atoms, and fewer than the number of frames)")
        percent, cumulative = write_variance(eigenvalues, trace, outdir / "variance.xvg")
        print("  Variance per principal component (all PCs in variance.xvg):")
        print_variance_table(eigenvalues, percent, cumulative, args.last)

        print(f"[4/5] Projections on PC{args.first}-PC{args.last} and RMSF (anaeig)...")
        projections, rmsf_xvg = run_anaeig(gmx, fit_gro, fit_xtc, ev_trr, pca_ndx, outdir,
                                           args.first, args.last, log_dir)
        old = outdir / "rmsip_halves.dat"
        if old.exists():
            old.unlink()
        if args.rmsip:
            times = np.loadtxt(projections[args.first], comments=("#", "@"), ndmin=2)[:, 0]
            run_rmsip_single(gmx, fit_xtc, times, fit_gro, pca_ndx, outdir, log_dir, args.rmsip_pcs)
    except (CommandError, AnalysisError) as e:
        print(f"Error: {e}", file=sys.stderr)
        return 1

    if args.no_plots:
        print("[5/5] Skipping plotting as requested (--no-plots)")
    elif plt is None:
        print("Matplotlib not available; cannot create plots. Install matplotlib or use --no-plots.", file=sys.stderr)
        return 3
    else:
        print("[5/5] Plots...")
        plot_variance(percent, cumulative, outdir)
        plot_projections(projections, outdir)
    plot_script = write_plot_script(outdir, projections, len(eigenvalues))

    print("Done. Outputs in:", outdir)
    if len(projections) >= 3:
        a, b, c = sorted(projections)[:3]
        print(f"3D plot of PC{a}/PC{b}/PC{c}: plot_xvg.py {projections[a].name} {projections[b].name} "
              f"{projections[c].name} --xy-correlation   (in {outdir})")
    print(f"All GROMACS commands have been logged to: {command_script}")
    print(f"plot_xvg.py commands for the plots, to edit and re-run: {plot_script}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
