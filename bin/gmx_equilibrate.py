#!/usr/bin/env python3
"""
GROMACS Equilibration Pipeline Script
Automates energy minimization and equilibration (NVT/NPT) with position restraints
Usage: python gmx_equilibrate.py <structure.gro> <topology.top> [options]
"""

import argparse
import subprocess
import sys
import os
import logging
from pathlib import Path
from datetime import datetime

# Global variable for command logging
_command_script_path = None

# Error hints for common failures
ERROR_HINTS = {
    'grompp': [
        "- Check MDP file syntax and parameters",
        "- Verify topology file is complete and valid",
        "- Ensure structure and topology match (atom counts)",
        "- Check for missing position restraint files if using restraints"
    ],
    'mdrun': [
        "- Check if system is stable (minimize first)",
        "- Verify temperature/pressure parameters are reasonable",
        "- Check if previous step completed successfully",
        "- Ensure sufficient disk space for output files"
    ],
    'genrestr': [
        "- Verify structure file exists and is valid",
        "- Check if protein/heavy atoms are present",
        "- Ensure index file has correct groups if using custom selection"
    ]
}

def setup_logging(verbose=False):
    """Configure logging for the script."""
    level = logging.DEBUG if verbose else logging.INFO
    logging.basicConfig(
        level=level,
        format='%(asctime)s - %(levelname)s - %(message)s',
        datefmt='%H:%M:%S'
    )

def set_command_script_path(path):
    """Set the global path for logging commands."""
    global _command_script_path
    _command_script_path = path
    with open(path, 'w') as f:
        f.write("#!/bin/bash\n")
        f.write("# GROMACS equilibration pipeline commands\n")
        f.write("# Generated by gmx_equilibrate.py\n")
        f.write("#\n")
        f.write(f"# Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
        f.write("#\n\n")
        f.write("set -e  # Exit on error\n\n")

def log_command_to_script(command, comment=None):
    """Append a command to the reproducibility script."""
    global _command_script_path
    if _command_script_path is None:
        return
    
    with open(_command_script_path, 'a') as f:
        if comment:
            f.write(f"\n# {comment}\n")
        f.write(f"{command}\n")

def run_gromacs_command(command, description, log_filename, dry_run=False, step_info=None):
    """Run a GROMACS command with logging and error handling."""
    logger = logging.getLogger(__name__)
    
    step_prefix = f"{step_info} " if step_info else ""
    
    logger.info("")
    logger.info("="*60)
    if dry_run:
        logger.info(f"{step_prefix}[DRY RUN] {description}")
    else:
        logger.info(f"{step_prefix}{description}")
    logger.debug(f"Command: {command}")
    if not dry_run:
        logger.debug(f"Log file: {log_filename}")
    logger.info("="*60)
    
    # Log to reproducibility script
    log_command_to_script(command, description)
    
    if dry_run:
        logger.info("[DRY RUN] Command logged but not executed")
        return True
    
    # Write command to log file
    with open(log_filename, 'w') as log_file:
        log_file.write(f"GROMACS Equilibration Log\n")
        log_file.write(f"Tool: {description}\n")
        log_file.write(f"Timestamp: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n")
        log_file.write(f"Command: {command}\n")
        log_file.write(f"{'='*60}\n\n")
    
    try:
        result = subprocess.run(command, shell=True, check=True,
                              capture_output=True, text=True)
        
        with open(log_filename, 'a') as log_file:
            if result.stdout:
                log_file.write("STDOUT:\n")
                log_file.write(result.stdout)
                log_file.write("\n")
            if result.stderr:
                log_file.write("STDERR:\n")
                log_file.write(result.stderr)
                log_file.write("\n")
            log_file.write(f"\nReturn code: {result.returncode}\n")
            log_file.write("✓ Command completed successfully\n")
        
        logger.info("✓ Success!")
        return True
        
    except subprocess.CalledProcessError as e:
        with open(log_filename, 'a') as log_file:
            if e.stdout:
                log_file.write("STDOUT:\n")
                log_file.write(e.stdout)
                log_file.write("\n")
            if e.stderr:
                log_file.write("STDERR:\n")
                log_file.write(e.stderr)
                log_file.write("\n")
            log_file.write(f"\nReturn code: {e.returncode}\n")
            log_file.write("✗ Command failed!\n")
        
        logger.error(f"❌ {description} failed!")
        logger.error(f"📋 Check log file: {log_filename}")
        logger.error(f"Return code: {e.returncode}")
        
        # Extract tool name for hints
        tool_name = description.split('(')[-1].split(')')[0] if '(' in description else None
        if tool_name and tool_name in ERROR_HINTS:
            logger.error("")
            logger.error("💡 Troubleshooting hints:")
            for hint in ERROR_HINTS[tool_name]:
                logger.error(f"   {hint}")
        
        return False

def create_em_mdp(filename, emtol=1000.0, emstep=0.01, nsteps=50000,
                  rcoulomb=1.0, rvdw=1.0, coulombtype='PME',
                  pme_order=4, fourierspacing=0.16, constraints='h-bonds'):
    """Create energy minimization MDP file."""
    content = f"""; Energy Minimization
; Generated by gmx_equilibrate.py

; Run control
integrator  = steep         ; Steepest descent minimizer
emtol       = {emtol}       ; Stop when max force < {emtol} kJ/mol/nm
emstep      = {emstep}      ; Energy step size (nm)
nsteps      = {nsteps}      ; Maximum number of steps

; Output control
nstlog      = 1000          ; Log output every 1000 steps
nstenergy   = 1000          ; Energy output every 1000 steps

; Neighbor searching
cutoff-scheme   = Verlet
nstlist         = 10
ns_type         = grid
pbc             = xyz

; Electrostatics
coulombtype     = {coulombtype}
rcoulomb        = {rcoulomb}
pme_order       = {pme_order}
fourierspacing  = {fourierspacing}

; Van der Waals
vdwtype         = Cut-off
rvdw            = {rvdw}

; Constraints
constraints     = {constraints}
"""
    with open(filename, 'w') as f:
        f.write(content)

def create_nvt_mdp(filename, dt=0.002, time_ps=100, ref_t=300,
                   tcoupl='V-rescale', tau_t=0.1,
                   gen_vel='yes', gen_temp=300, gen_seed=-1,
                   continuation='no', constraints='h-bonds',
                   lincs_order=4, lincs_iter=1,
                   rcoulomb=1.0, rvdw=1.0, coulombtype='PME',
                   pme_order=4, fourierspacing=0.16,
                   nstlog=5000, nstenergy=5000, nstxout_compressed=5000,
                   define=''):
    """Create NVT equilibration MDP file."""
    nsteps = int(time_ps / dt)
    
    content = f"""; NVT Equilibration
; Generated by gmx_equilibrate.py

; Run control
integrator  = md            ; Leap-frog integrator
dt          = {dt}          ; Timestep (ps)
nsteps      = {nsteps}      ; {time_ps} ps

; Output control
nstlog                  = {nstlog}
nstenergy               = {nstenergy}
nstxout-compressed      = {nstxout_compressed}
compressed-x-precision  = 1000

; Neighbor searching
cutoff-scheme   = Verlet
nstlist         = 10
ns_type         = grid
pbc             = xyz

; Electrostatics
coulombtype     = {coulombtype}
rcoulomb        = {rcoulomb}
pme_order       = {pme_order}
fourierspacing  = {fourierspacing}

; Van der Waals
vdwtype         = Cut-off
rvdw            = {rvdw}
DispCorr        = EnerPres

; Temperature coupling
tcoupl          = {tcoupl}
tc-grps         = System
tau_t           = {tau_t}
ref_t           = {ref_t}

; Pressure coupling
pcoupl          = no

; Velocity generation
gen_vel         = {gen_vel}
gen_temp        = {gen_temp}
gen_seed        = {gen_seed}

; Constraints
constraints         = {constraints}
constraint_algorithm = lincs
lincs_order         = {lincs_order}
lincs_iter          = {lincs_iter}

; Continuation
continuation    = {continuation}
"""
    
    if define:
        content = content.replace('; Run control', f'; Preprocessor defines\ndefine = {define}\n\n; Run control')
    
    with open(filename, 'w') as f:
        f.write(content)

