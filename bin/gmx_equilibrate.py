def generate_position_restraints(structure_file, output_file, selection='heavy',
                                force_constant=1000, dry_run=False):
    """Generate position restraint file using gmx genrestr."""
    logger = logging.getLogger(__name__)
    
    # Determine selection string
    select_map = {
        'heavy': '3',      # Heavy atoms (non-hydrogen)
        'backbone': '4',   # Backbone atoms
        'protein': '1',    # Entire protein
        'ca': '3'          # C-alpha atoms (user would need custom index)
    }
    
    selection_input = select_map.get(selection, '3')
    
    cmd = f"echo {selection_input} | gmx genrestr -f {structure_file} -o {output_file} -fc {force_constant} {force_constant} {force_constant}"
    
    logger.info(f"Generating position restraints ({selection}) with fc={force_constant}")
    log_command_to_script(cmd, f"Generate position restraints ({selection})")
    
    if dry_run:
        logger.info("[DRY RUN] Position restraint generation skipped")
        return True
    
    try:
        result = subprocess.run(cmd, shell=True, check=True, capture_output=True, text=True)
        logger.info(f"✓ Created {output_file}")
        return True
    except subprocess.CalledProcessError as e:
        logger.error(f"❌ Failed to generate position restraints")
        logger.error(f"Return code: {e.returncode}")
        if 'genrestr' in ERROR_HINTS:
            logger.error("\n💡 Troubleshooting hints:")
            for hint in ERROR_HINTS['genrestr']:
                logger.error(f"   {hint}")
        return False

def run_equilibration_pipeline(args):
    """Run the complete equilibration pipeline."""
    logger = logging.getLogger(__name__)
    
    # Initialize command logging
    commands_file = Path.cwd() / args.commands_file
    set_command_script_path(commands_file)
    
    # Validate input files
    if not os.path.exists(args.structure):
        logger.error(f"❌ Structure file not found: {args.structure}")
        return False
    if not os.path.exists(args.topology):
        logger.error(f"❌ Topology file not found: {args.topology}")
        return False
    
    # Configuration summary
    logger.info("")
    logger.info("="*60)
    logger.info("GROMACS EQUILIBRATION PIPELINE")
    logger.info("="*60)
    
    if args.dry_run:
        logger.info("")
        logger.info("🔍 DRY RUN MODE: Commands will be logged but not executed")
    
    logger.info("")
    logger.info("📋 Configuration:")
    logger.info(f"  Structure:       {args.structure}")
    logger.info(f"  Topology:        {args.topology}")
    logger.info(f"  Output prefix:   {args.prefix}")
    logger.info(f"  Temperature:     {args.temp} K")
    logger.info(f"  Pressure:        {args.pressure} bar")
    logger.info(f"  T-coupling:      {args.tcoupl}")
    logger.info(f"  P-coupling:      {args.pcoupl}")
    logger.info("")
    logger.info("📊 Pipeline stages:")
    logger.info(f"  [1/4] Energy minimization:    {args.time_em} steps")
    logger.info(f"  [2/4] NVT (restrained):       {args.time_nvt} ps")
    logger.info(f"  [3/4] NPT (restrained):       {args.time_npt1} ps")
    logger.info(f"  [4/4] NPT (unrestrained):     {args.time_npt2} ps")
    logger.info("")
    logger.info(f"All commands logged to: {commands_file}")
    logger.info("")
    
    # Get advanced parameters (use defaults if not specified)
    dt = args.dt if args.dt else 0.002
    tau_t = args.tau_t if args.tau_t else 0.1
    tau_p = args.tau_p if args.tau_p else 2.0
    rcoulomb = args.rcoulomb if args.rcoulomb else 1.0
    rvdw = args.rvdw if args.rvdw else 1.0
    lincs_order = args.lincs_order if args.lincs_order else 4
    constraints = args.constraints if args.constraints else 'h-bonds'
    emtol = args.emtol if args.emtol else 1000.0
    
    prefix = args.prefix
    
    # Stage 1: Energy Minimization
    logger.info("")
    logger.info("[1/4] Energy Minimization")
    logger.info("-" * 60)
    
    em_mdp = f"{prefix}_em.mdp"
    em_tpr = f"{prefix}_em.tpr"
    em_gro = f"{prefix}_em.gro"
    em_log = f"{prefix}_em.log"
    em_edr = f"{prefix}_em.edr"
    
    create_em_mdp(em_mdp, emtol=emtol, nsteps=args.time_em,
                  rcoulomb=rcoulomb, rvdw=rvdw, constraints=constraints)
    logger.info(f"✓ Created {em_mdp}")
    
    grompp_cmd = f"gmx grompp -f {em_mdp} -c {args.structure} -p {args.topology} -o {em_tpr} -maxwarn 1"
    if not run_gromacs_command(grompp_cmd, "Prepare EM (grompp)", f"{prefix}_em_grompp.log",
                               dry_run=args.dry_run, step_info="[1/4]"):
        return False
    
    mdrun_cmd = f"gmx mdrun -deffnm {prefix}_em"
    if not run_gromacs_command(mdrun_cmd, "Run EM (mdrun)", f"{prefix}_em_mdrun.log",
                               dry_run=args.dry_run, step_info="[1/4]"):
        return False
    
    # Stage 2: NVT with restraints
    logger.info("")
    logger.info("[2/4] NVT Equilibration (restrained)")
    logger.info("-" * 60)
    
    # Generate position restraints
    posre_file = "posre_heavy.itp"
    if not generate_position_restraints(em_gro if not args.dry_run else args.structure,
                                       posre_file, selection='heavy',
                                       force_constant=1000, dry_run=args.dry_run):
        logger.warning("⚠️  Position restraint generation failed, continuing without restraints")
        posre_define = ''
    else:
        posre_define = '-DPOSRES'
    
    nvt_mdp = f"{prefix}_nvt.mdp"
    nvt_tpr = f"{prefix}_nvt.tpr"
    nvt_gro = f"{prefix}_nvt.gro"
    
    create_nvt_mdp(nvt_mdp, dt=dt, time_ps=args.time_nvt, ref_t=args.temp,
                   tcoupl=args.tcoupl, tau_t=tau_t,
                   gen_vel='yes', gen_temp=args.temp, gen_seed=-1,
                   continuation='no', constraints=constraints,
                   lincs_order=lincs_order, rcoulomb=rcoulomb, rvdw=rvdw,
                   define=posre_define)
    logger.info(f"✓ Created {nvt_mdp}")
    
    grompp_cmd = f"gmx grompp -f {nvt_mdp} -c {em_gro} -r {em_gro} -p {args.topology} -o {nvt_tpr} -maxwarn 1"
    if not run_gromacs_command(grompp_cmd, "Prepare NVT (grompp)", f"{prefix}_nvt_grompp.log",
                               dry_run=args.dry_run, step_info="[2/4]"):
        return False
    
    mdrun_cmd = f"gmx mdrun -deffnm {prefix}_nvt"
    if not run_gromacs_command(mdrun_cmd, "Run NVT (mdrun)", f"{prefix}_nvt_mdrun.log",
                               dry_run=args.dry_run, step_info="[2/4]"):
        return False
    
    # Stage 3: NPT with restraints
    logger.info("")
    logger.info("[3/4] NPT Equilibration (restrained)")
    logger.info("-" * 60)
    
    npt1_mdp = f"{prefix}_npt1.mdp"
    npt1_tpr = f"{prefix}_npt1.tpr"
    npt1_gro = f"{prefix}_npt1.gro"
    
    create_npt_mdp(npt1_mdp, dt=dt, time_ps=args.time_npt1, ref_t=args.temp, ref_p=args.pressure,
                   tcoupl=args.tcoupl, tau_t=tau_t,
                   pcoupl='Berendsen', tau_p=tau_p,  # Use Berendsen for equilibration
                   gen_vel='no', continuation='yes',
                   constraints=constraints, lincs_order=lincs_order,
                   rcoulomb=rcoulomb, rvdw=rvdw,
                   define=posre_define)
    logger.info(f"✓ Created {npt1_mdp}")
    
    grompp_cmd = f"gmx grompp -f {npt1_mdp} -c {nvt_gro} -r {em_gro} -t {prefix}_nvt.cpt -p {args.topology} -o {npt1_tpr} -maxwarn 1"
    if not run_gromacs_command(grompp_cmd, "Prepare NPT1 (grompp)", f"{prefix}_npt1_grompp.log",
                               dry_run=args.dry_run, step_info="[3/4]"):
        return False
    
    mdrun_cmd = f"gmx mdrun -deffnm {prefix}_npt1"
    if not run_gromacs_command(mdrun_cmd, "Run NPT1 (mdrun)", f"{prefix}_npt1_mdrun.log",
                               dry_run=args.dry_run, step_info="[3/4]"):
        return False
    
    # Stage 4: NPT without restraints
    logger.info("")
    logger.info("[4/4] NPT Equilibration (unrestrained)")
    logger.info("-" * 60)
    
    npt2_mdp = f"{prefix}_npt2.mdp"
    npt2_tpr = f"{prefix}_npt2.tpr"
    npt2_gro = f"{prefix}_npt2.gro"
    
    # Use user's pcoupl choice (could be Parrinello-Rahman for final stage)
    create_npt_mdp(npt2_mdp, dt=dt, time_ps=args.time_npt2, ref_t=args.temp, ref_p=args.pressure,
                   tcoupl=args.tcoupl, tau_t=tau_t,
                   pcoupl=args.pcoupl, tau_p=tau_p,
                   gen_vel='no', continuation='yes',
                   constraints=constraints, lincs_order=lincs_order,
                   rcoulomb=rcoulomb, rvdw=rvdw,
                   define='')  # No restraints
    logger.info(f"✓ Created {npt2_mdp}")
    
    grompp_cmd = f"gmx grompp -f {npt2_mdp} -c {npt1_gro} -t {prefix}_npt1.cpt -p {args.topology} -o {npt2_tpr} -maxwarn 1"
    if not run_gromacs_command(grompp_cmd, "Prepare NPT2 (grompp)", f"{prefix}_npt2_grompp.log",
                               dry_run=args.dry_run, step_info="[4/4]"):
        return False
    
    mdrun_cmd = f"gmx mdrun -deffnm {prefix}_npt2"
    if not run_gromacs_command(mdrun_cmd, "Run NPT2 (mdrun)", f"{prefix}_npt2_mdrun.log",
                               dry_run=args.dry_run, step_info="[4/4]"):
        return False
    
    # Summary
    logger.info("")
    logger.info("="*60)
    if args.dry_run:
        logger.info("✅ DRY RUN COMPLETED SUCCESSFULLY!")
        logger.info("="*60)
        logger.info("")
        logger.info(f"📝 Commands saved to: {commands_file}")
        logger.info("")
        logger.info("📋 Pipeline will produce:")
        logger.info(f"  1. EM output:        {prefix}_em.gro")
        logger.info(f"  2. NVT output:       {prefix}_nvt.gro")
        logger.info(f"  3. NPT1 output:      {prefix}_npt1.gro")
        logger.info(f"  4. NPT2 output:      {prefix}_npt2.gro ⭐")
        logger.info("")
        logger.info("🚀 To execute the pipeline:")
        logger.info(f"   bash {commands_file}")
        logger.info("   OR")
        logger.info(f"   python {sys.argv[0]} {args.structure} {args.topology} [options]")
    else:
        logger.info("✅ EQUILIBRATION COMPLETED SUCCESSFULLY!")
        logger.info("="*60)
        logger.info("")
        logger.info("📁 Output files:")
        logger.info(f"  Final structure:      {prefix}_npt2.gro ⭐")
        logger.info(f"  Checkpoint:           {prefix}_npt2.cpt")
        logger.info(f"  Energy files:         {prefix}_*.edr")
        logger.info(f"  Log files:            {prefix}_*_mdrun.log")
        logger.info("")
        logger.info(f"📝 Reproducibility:     {commands_file}")
        logger.info("")
        logger.info("🎯 Next steps:")
        logger.info("  1. Analyze equilibration (temperature, pressure, density)")
        logger.info("  2. Production MD run")
        logger.info("  3. Trajectory analysis")
    
    logger.info("="*60)
    return True

def main():
    parser = argparse.ArgumentParser(
        description="Automate GROMACS equilibration pipeline (EM → NVT → NPT)",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Basic usage with defaults
  gmx_equilibrate.py protein_ions.gro protein.top
  
  # Custom temperature and longer equilibration
  gmx_equilibrate.py protein_ions.gro protein.top --temp 310 --time-npt2 1000
  
  # Preview commands without executing
  gmx_equilibrate.py protein_ions.gro protein.top --dry-run
  
  # Advanced: custom coupling parameters
  gmx_equilibrate.py protein_ions.gro protein.top --tau-t 0.5 --tau-p 5.0
  
  # Use Parrinello-Rahman barostat for final NPT
  gmx_equilibrate.py protein_ions.gro protein.top --pcoupl Parrinello-Rahman
        """)
    
    # Positional arguments
    parser.add_argument('structure', help='Input structure file (.gro)')
    parser.add_argument('topology', help='Topology file (.top)')
    
    # Basic parameters
    parser.add_argument('--prefix', default='equil', help='Output file prefix (default: equil)')
    parser.add_argument('--temp', type=float, default=300, help='Temperature in K (default: 300)')
